    private static readonly DateTime Start = new DateTime(1943, 4, 14).AddDays(-Enumerable.Range(MinYear, 2000 - MinYear).Sum(y => Table[y].Sum()));

    /// <summary>Converts an AD date to a BS year, month (1-12) and day, or null when outside the supported range.</summary>
    public static (int Year, int Month, int Day)? ToBs(DateTime ad)
    {
        var days = (int)(ad.Date - Start).TotalDays;
        if (days < 0) return null;
        for (var year = MinYear; year <= MaxYear; year++)
        {
            var months = Table[year];
            var length = months.Sum();
            if (days >= length) { days -= length; continue; }
            for (var m = 0; m < 12; m++)
            {
                if (days < months[m]) return (year, m + 1, days + 1);
                days -= months[m];
            }
        }
        return null;
    }

    /// <summary>Formats like "12 Kartik 2083"; empty when the date is outside the supported range.</summary>
    public static string Format(DateTime ad)
    {
        var bs = ToBs(ad);
        return bs is { } d ? $"{d.Day} {MonthNames[d.Month - 1]} {d.Year}" : "";
    }

    public static int DaysInMonth(int year, int month) => Table[year][month - 1];

    /// <summary>Converts a BS date to AD, or null when outside the supported range.</summary>
    public static DateTime? FromBs(int year, int month, int day)
    {
        if (year < MinYear || year > MaxYear || month < 1 || month > 12) return null;
        var days = 0;
        for (var y = MinYear; y < year; y++) days += Table[y].Sum();
        for (var m = 1; m < month; m++) days += Table[year][m - 1];
        return Start.AddDays(days + day - 1);
    }
